// Generates ios/Wishlist/Core/Translations.swift from the web app's dictionaries so both clients
// always show the same texts. Run after changing frontend/src/app/core/i18n/{en,de}.ts:
//   node ios/scripts/generate-translations.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const i18n = path.join(root, 'frontend/src/app/core/i18n');
const { en } = await import(path.join(i18n, 'en.ts'));
const { de } = await import(path.join(i18n, 'de.ts'));

const caseName = (key) => {
  const name = key
    .split(/[.\-_]/)
    .filter(Boolean)
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('');
  return /^\d/.test(name) ? `_${name}` : name;
};

const literal = (value) =>
  `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\n', '\\n')}"`;

const entry = (value) =>
  typeof value === 'string' ? `.text(${literal(value)})` : `.plural(one: ${literal(value.one)}, other: ${literal(value.other)})`;

const dictionary = (name, values) =>
  [
    `  static let ${name}: [TKey: TValue] = [`,
    ...Object.entries(values).map(([key, value]) => `    .${caseName(key)}: ${entry(value)},`),
    '  ]',
  ].join('\n');

const keys = Object.keys(en);
const names = new Set(keys.map(caseName));
if (names.size !== keys.length) throw new Error('Two translation keys map to the same Swift case name');
for (const key of Object.keys(de)) if (!(key in en)) throw new Error(`German key "${key}" is missing in English`);

const output = `// Generated by ios/scripts/generate-translations.mjs from the web app's dictionaries. Do not edit.

nonisolated enum TKey: String, CaseIterable, Sendable {
${keys.map((key) => `  case ${caseName(key)} = ${literal(key)}`).join('\n')}
}

nonisolated enum TValue: Sendable, Equatable {
  case text(String)
  case plural(one: String, other: String)
}

nonisolated enum Translations {
${dictionary('en', en)}

${dictionary('de', de)}
}
`;

const target = path.join(root, 'ios/Wishlist/Core/Translations.swift');
writeFileSync(target, output);
console.log(`Wrote ${keys.length} keys to ${path.relative(root, target)}`);
